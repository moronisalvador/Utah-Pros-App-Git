/**
 * ════════════════════════════════════════════════
 * FILE: contractor-compliance-public.js
 * ════════════════════════════════════════════════
 *
 * WHAT THIS DOES (plain language):
 *   Accepts a contractor's requested document without asking them to sign in.
 *   It checks the one-time link and the file before saving it for staff review.
 *
 * DEPENDS ON:
 *   Packages:  none
 *   Internal:  supabase.js, contractor-compliance.js
 *   Data:      reads → contractor_compliance_requests
 *              writes → Storage, contractor_compliance_documents, contractor_compliance_public_attempts
 *
 * NOTES / GOTCHAS:
 *   - The raw link token is accepted only in a request header, never a URL.
 * ════════════════════════════════════════════════
 *
 * public: scoped, revocable contractor upload capability. The browser gets no
 * anonymous table/storage access; this Worker hashes and resolves the token.
 */
import { fetchWithTimeout } from '../lib/http.js';
import { supabase } from '../lib/supabase.js';
import {
  complianceEnabled,
  CONTRACTOR_COMPLIANCE_BUCKET,
  genericPublicResponse,
  randomStoragePath,
  safeOriginalFilename,
  sha256Hex,
  tokenDigest,
  validateDocumentDates,
  validDocumentType,
  validateContractorDocument,
} from '../lib/contractor-compliance.js';

function response(body, status) {
  return new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' } });
}
function rawToken(request) {
  // Do not accept a query/form token: access logs and multipart diagnostics can
  // retain them. The SPA extracts the route capability and sends it only here.
  return request.headers.get('X-Contractor-Upload-Token') || '';
}
function publicProjection(row) {
  return {
    requested_types: row.requested_document_types,
    expires_at: row.expires_at,
    closed: false,
  };
}
async function lookupRequest(db, request) {
  const digest = await tokenDigest(rawToken(request));
  if (!digest) return null;
  try {
    const value = await db.rpc('contractor_compliance_public_request', { p_token_digest: digest });
    const row = Array.isArray(value) ? value[0] : value;
    return row?.request_id && row?.contractor_id ? { row, digest } : null;
  } catch { return null; }
}

export async function onRequestGet({ request, env }) {
  if (!complianceEnabled(env)) return response({ error: 'Not found' }, 404);
  if (String(env.CONTRACTOR_COMPLIANCE_RATE_LIMIT_SALT || '').length < 16) return response(genericPublicResponse(), 404);
  const found = await lookupRequest(supabase(env, fetchWithTimeout), request);
  if (!found) return response(genericPublicResponse(), 404);
  return response(publicProjection(found.row), 200);
}

export async function onRequestPost({ request, env }) {
  if (!complianceEnabled(env)) return response({ error: 'Not found' }, 404);
  const db = supabase(env, fetchWithTimeout);
  const salt = String(env.CONTRACTOR_COMPLIANCE_RATE_LIMIT_SALT || '');
  if (salt.length < 16) return response(genericPublicResponse(), 404);
  const contentLength = Number(request.headers.get('Content-Length') || 0);
  if (Number.isFinite(contentLength) && contentLength > 7 * 1024 * 1024) {
    return response({ error: 'Upload a PDF, JPEG, or PNG document no larger than 6 MiB.' }, 413);
  }
  let form;
  try { form = await request.formData(); } catch { return response(genericPublicResponse(), 400); }
  const found = await lookupRequest(db, request);
  if (!found) return response(genericPublicResponse(), 404);
  // The SQL function both rate-bounds and reserves an attempt. It receives a
  // one-way IP digest generated by the platform boundary, never the raw IP.
  let attempt;
  try {
    const ip = request.headers.get('CF-Connecting-IP') || '';
    const ipDigest = ip ? await sha256Hex(new TextEncoder().encode(`${salt}:${ip}`)) : null;
    attempt = await db.rpc('contractor_compliance_record_public_attempt', {
      p_request_id: found.row.request_id,
      p_token_digest: found.digest,
      p_ip_digest: ipDigest,
    });
  } catch { return response(genericPublicResponse(), 429); }
  if (attempt === false || attempt?.allowed === false) return response(genericPublicResponse(), 429);
  const type = String(form.get('document_type') || '');
  const allowed = Array.isArray(found.row.requested_document_types) && found.row.requested_document_types.includes(type);
  if (!validDocumentType(type) || !allowed) return response(genericPublicResponse(), 404);
  let dates;
  try {
    dates = validateDocumentDates(type, {
      effectiveDate: form.get('effective_date'),
      expirationDate: form.get('expiration_date'),
      taxYear: form.get('tax_year'),
    });
  } catch (error) {
    return response({ error: error.message, code: error.code }, error.status || 400);
  }
  const file = form.get('file');
  if (!file || typeof file.arrayBuffer !== 'function' || !Number.isSafeInteger(file.size) || file.size <= 0 || file.size > 6 * 1024 * 1024) {
    return response({ error: 'Upload a PDF, JPEG, or PNG document no larger than 6 MiB.' }, 400);
  }
  let checked;
  try { checked = validateContractorDocument(await file.arrayBuffer(), file.type); } catch (error) {
    return response({ error: error.message, code: error.code }, error.status || 400);
  }
  const path = randomStoragePath(found.row.contractor_id, checked.extension);
  let stored = false;
  try {
    const contentSha256 = await sha256Hex(checked.bytes);
    await db.uploadStorage(CONTRACTOR_COMPLIANCE_BUCKET, path, checked.bytes, checked.mimeType, { upsert: false });
    stored = true;
    await db.rpc('contractor_compliance_ingest_document', {
      p_request_id: found.row.request_id,
      p_contractor_id: found.row.contractor_id,
      p_document_type: type,
      p_source: 'public_upload',
      p_storage_bucket: CONTRACTOR_COMPLIANCE_BUCKET,
      p_storage_path: path,
      p_original_filename: safeOriginalFilename(file.name),
      p_mime_type: checked.mimeType,
      p_byte_size: checked.byteSize,
      p_content_sha256: contentSha256,
      p_effective_date: dates.effectiveDate,
      p_expiration_date: dates.expirationDate,
      p_tax_year: dates.taxYear,
    });
  } catch {
    if (stored) await db.deleteStorage?.(CONTRACTOR_COMPLIANCE_BUCKET, path).catch(() => {});
    return response({ error: 'Your document could not be saved. Please try again later.' }, 503);
  }
  return response({ ok: true, message: 'Your document was received for review.' }, 201);
}
